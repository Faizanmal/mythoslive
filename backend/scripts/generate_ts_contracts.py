"""Generate the frontend contract types from the canonical Pydantic models."""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.contracts.events import (
    ActorIdentity,
    EngineRealtimeEvent,
    EngineRealtimeSnapshot,
    GameEvent,
    RealtimeConnectionStatus,
    RealtimeGameEvent,
    RealtimeWorldSnapshot,
    SimStatus,
    WorldSnapshot,
)

TARGET = Path(__file__).resolve().parents[2] / "frontend/src/lib/contracts.generated.ts"


def ts_type(schema: dict[str, object]) -> str:
    if "const" in schema:
        value = schema["const"]
        return (
            repr(value)
            if isinstance(value, str)
            else str(value).lower()
            if isinstance(value, bool)
            else str(value)
        )
    if "anyOf" in schema:
        variants = [ts_type(item) for item in schema["anyOf"] if isinstance(item, dict)]
        return " | ".join(variants)
    ref = schema.get("$ref")
    if isinstance(ref, str):
        return ref.rsplit("/", 1)[-1]
    kind = schema.get("type")
    if kind == "null":
        return "null"
    if kind == "string":
        if isinstance(schema.get("enum"), list):
            return " | ".join(repr(value) for value in schema["enum"])
        return "string"
    if kind in ("integer", "number"):
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "array":
        return f"Array<{ts_type(schema.get('items', {}))}>"
    if kind == "object" or "additionalProperties" in schema:
        additional = schema.get("additionalProperties", True)
        return (
            f"Record<string, {ts_type(additional) if isinstance(additional, dict) else 'unknown'}>"
        )
    return "unknown"


def render_model(model: type) -> str:
    schema = model.model_json_schema()
    fields = schema.get("properties", {})
    rows = [f"export interface {model.__name__} {{"]
    for name, field_schema in fields.items():
        rows.append(f"  {name}: {ts_type(field_schema)};")
    rows.append("}")
    return "\n".join(rows)


MODELS = [
    ActorIdentity,
    GameEvent,
    WorldSnapshot,
    RealtimeGameEvent,
    RealtimeWorldSnapshot,
    RealtimeConnectionStatus,
    EngineRealtimeEvent,
    EngineRealtimeSnapshot,
    SimStatus,
]

TARGET.parent.mkdir(parents=True, exist_ok=True)
TARGET.write_text(
    "// Generated by backend/scripts/generate_ts_contracts.py; do not edit by hand.\n\n"
    + "\n\n".join(render_model(model) for model in MODELS)
    + "\n\nexport type RealtimeMessage = RealtimeGameEvent | RealtimeWorldSnapshot "
    + "| RealtimeConnectionStatus | EngineRealtimeEvent | EngineRealtimeSnapshot;\n",
    encoding="utf-8",
)
print(f"Generated {TARGET}")
